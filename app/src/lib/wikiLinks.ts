/**
 * Конспекты и «О курсе», синхронизированные с GitHub (PROMPT 25), — это Obsidian-хранилище:
 * ссылки в них написаны как `[[Название]]` или `[[Название|Подпись]]`, а не обычным markdown
 * `[Подпись](url)`. ReactMarkdown/remark ничего не знает про этот синтаксис и печатает такие
 * ссылки как есть, буквально со скобками.
 *
 * convertWikiLinks переписывает их в обычные markdown-ссылки с меткой-путём `wikilink/...`
 * ДО парсинга — тогда remark разбирает их как самые обычные ссылки, а WikiLinkAnchor
 * (см. WikiLink.tsx) уже во время рендера решает, ведёт ли эта ссылка на что-то реально
 * синхронизированное в приложении (конспект/предмет), или это ссылка на файл, которого
 * здесь нет (другой поток, README вне папки потока, CONTRIBUTING и т.п.).
 *
 * Метка нарочно БЕЗ двоеточия (не "wikilink:xxx", а "wikilink/xxx") — ReactMarkdown по
 * умолчанию прогоняет все href через санитайзер, который бланкует любую незнакомую
 * URL-схему (protocol:...) в пустую строку ради защиты от javascript:-ссылок. Строка без
 * двоеточия схемой не считается и проходит как обычный относительный путь без изменений.
 *
 * `\\?\|` перед подписью — внутри ячеек markdown-таблиц (GFM) символ `|` экранируется
 * как `\|`, иначе он оборвал бы столбец; при чтении сырого текста (до парсинга таблицы)
 * это ещё буквально обратный слеш + вертикальная черта, и без учёта этого экранирования
 * слеш попадал бы в конец target — ссылка на конспект внутри таблицы никогда бы не резолвилась.
 */
const WIKI_LINK_PATTERN = /\[\[([^\]|]+?)(?:\\?\|([^\]]+?))?\]\]/g;

export function convertWikiLinks(markdown: string): string {
  return markdown.replace(WIKI_LINK_PATTERN, (_match, target: string, label: string | undefined) => {
    const display = (label ?? target).trim();
    return `[${display}](${WIKI_LINK_PREFIX}${encodeURIComponent(target.trim())})`;
  });
}

export const WIKI_LINK_PREFIX = 'wikilink/';
